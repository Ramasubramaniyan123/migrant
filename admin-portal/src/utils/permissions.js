/**
 * Role → permission map. Enforcement happens here in the prototype;
 * in production the Spring Boot backend must re-check every permission.
 */
export const PERMISSIONS = {
  DASHBOARD_VIEW: 'dashboard:view',
  USERS_VIEW: 'users:view',
  USERS_MANAGE: 'users:manage',
  USERS_SUSPEND: 'users:suspend',
  COMMUNITIES_VIEW: 'communities:view',
  COMMUNITIES_MANAGE: 'communities:manage',
  LANGUAGES_MANAGE: 'languages:manage',
  LOCATIONS_MANAGE: 'locations:manage',
  MODERATION_VIEW: 'moderation:view',
  MODERATION_RESOLVE: 'moderation:resolve',
  POSTS_MANAGE: 'posts:manage',
  ANALYTICS_VIEW: 'analytics:view',
  ADMINS_MANAGE: 'admins:manage',
  AUDIT_VIEW: 'audit:view',
  NOTIFICATIONS_SEND: 'notifications:send',
  EVENTS_MANAGE: 'events:manage',
  SETTINGS_MANAGE: 'settings:manage'
};
export const ROLE_PERMISSIONS = {
  SUPER_ADMIN: new Set(Object.values(PERMISSIONS)),
  ADMIN: new Set([PERMISSIONS.DASHBOARD_VIEW, PERMISSIONS.USERS_VIEW, PERMISSIONS.USERS_MANAGE, PERMISSIONS.USERS_SUSPEND, PERMISSIONS.COMMUNITIES_VIEW, PERMISSIONS.COMMUNITIES_MANAGE, PERMISSIONS.LANGUAGES_MANAGE, PERMISSIONS.LOCATIONS_MANAGE, PERMISSIONS.MODERATION_VIEW, PERMISSIONS.MODERATION_RESOLVE, PERMISSIONS.POSTS_MANAGE, PERMISSIONS.ANALYTICS_VIEW, PERMISSIONS.AUDIT_VIEW, PERMISSIONS.NOTIFICATIONS_SEND, PERMISSIONS.EVENTS_MANAGE, PERMISSIONS.SETTINGS_MANAGE]),
  MODERATOR: new Set([PERMISSIONS.DASHBOARD_VIEW, PERMISSIONS.USERS_VIEW, PERMISSIONS.USERS_SUSPEND, PERMISSIONS.COMMUNITIES_VIEW, PERMISSIONS.MODERATION_VIEW, PERMISSIONS.MODERATION_RESOLVE, PERMISSIONS.POSTS_MANAGE, PERMISSIONS.EVENTS_MANAGE]),
  SUPPORT: new Set([PERMISSIONS.DASHBOARD_VIEW, PERMISSIONS.USERS_VIEW, PERMISSIONS.USERS_MANAGE, PERMISSIONS.COMMUNITIES_VIEW, PERMISSIONS.MODERATION_VIEW, PERMISSIONS.NOTIFICATIONS_SEND]),
  ANALYST: new Set([PERMISSIONS.DASHBOARD_VIEW, PERMISSIONS.USERS_VIEW, PERMISSIONS.COMMUNITIES_VIEW, PERMISSIONS.ANALYTICS_VIEW, PERMISSIONS.AUDIT_VIEW])
};
export function hasPermission(role, permission) {
  if (!role) return false;
  return ROLE_PERMISSIONS[role]?.has(permission) ?? false;
}
export function hasAnyPermission(role, permissions) {
  return permissions.some(p => hasPermission(role, p));
}
